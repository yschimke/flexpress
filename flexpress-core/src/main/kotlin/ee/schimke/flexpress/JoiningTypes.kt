package ee.schimke.flexpress

// Generated from the Unicode Character Database's ArabicShaping.txt (Unicode 18.0): the explicit
// Joining_Type of each character listed there, as start, end and type triples. Characters not
// listed are Transparent when their general category is Mn, Me or Cf, and Non_Joining otherwise.

/** Unicode `Joining_Type`, as the Arabic shaping algorithm uses it. */
internal enum class JoiningType {
  /** Joins on the right (the preceding letter) only, as alef. */
  RIGHT,
  /** Joins on both sides, as beh. */
  DUAL,
  /** Joins on the left (the following letter) only. */
  LEFT,
  /** Causes joining without taking a form, as tatweel and the zero width joiner. */
  JOIN_CAUSING,
  /** Skipped by joining, as the vowel marks. */
  TRANSPARENT,
  /** Does not join. */
  NON_JOINING,
}

/** [cp]'s joining type. */
internal fun joiningType(cp: Int): JoiningType {
  var lo = 0
  var hi = JOINING_RANGES.size / 3 - 1
  while (lo <= hi) {
    val mid = (lo + hi) ushr 1
    when {
      JOINING_RANGES[mid * 3 + 1] < cp -> lo = mid + 1
      JOINING_RANGES[mid * 3] > cp -> hi = mid - 1
      else -> return JoiningType.entries[JOINING_RANGES[mid * 3 + 2]]
    }
  }
  return when (Character.getType(cp)) {
    Character.NON_SPACING_MARK.toInt(),
    Character.ENCLOSING_MARK.toInt(),
    Character.FORMAT.toInt() -> JoiningType.TRANSPARENT
    else -> JoiningType.NON_JOINING
  }
}

